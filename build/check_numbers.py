"""본문 '숫자로 한 번 해 보기'·대화·퀴즈 숫자와 평가 점수 검산. python3 build/check_numbers.py"""
import math, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from content_a import P1, P2, P4
from content_c import P3
from content_b import P5, P6, P7
ok = True
def chk(name, got, want, tol=0.01):
    global ok
    good = abs(got - want) <= tol
    ok &= good
    print(("OK " if good else "XX "), name, round(got, 4), "기대", want)
# 목차 스타일 지도
chk("0 거리 제곱합", 0.6 ** 2 + 0.4 ** 2, 0.52); chk("0 거리", math.sqrt(0.52), 0.72, 0.005)
# 1부
chk("1-1 그림자 1단계 색 수", 5 * (1 + 1), 10); chk("1-1 2단계", 5 * (1 + 2), 15); chk("1-1 하이라이트 포함", 5 * (1 + 2 + 1), 20); chk("1-1 대화 3단계", 5 * (1 + 3), 20)
chk("1-3 선 30", 12 * 30, 360); chk("1-3 선 60", 12 * 60, 720); chk("1-3 5초", 720 * 5, 3600); chk("1-3 퀴즈", 12 * 40, 480)
chk("1-3 대화 가닥 4", 10 + 2 * 4, 18); chk("1-3 대화 가닥 14", 10 + 2 * 14, 38); chk("1-3 2배 넘게", (12 * 38) / (12 * 18), 2.11, 0.01)
# 2부
chk("2-1 굵기 비", 3.6 / 1.2, 3); chk("2-1 붓", 4.5 / 0.9, 5); chk("2-1 퀴즈", 4 / 2, 2)
# 3부
chk("3-1 휜 정도 20", 20 / 200, 0.1); chk("3-1 50", 50 / 200, 0.25); chk("3-1 80", 80 / 200, 0.4)
chk("3-2 망점 넓이", math.pi * 2 * 2, 12.57, 0.01); chk("3-2 망점 비율", math.pi * 4 / 64, 0.196, 0.001); chk("3-2 반지름 3", math.pi * 9 / 64, 0.44, 0.003)
chk("3-2 패널 dens3 반지름", 1.25 + 0.25 * 3, 2.0)
chk("3-4 분홍 회색값", 0.299 * 232 + 0.587 * 138 + 0.114 * 170, 170, 0.5); chk("3-4 라벤더 회색값", 0.299 * 190 + 0.587 * 170 + 0.114 * 225, 182, 0.5)
chk("3-4 분홍 성분", 0.299 * 232, 69.4, 0.05); chk("3-4 차이", 182 - 170, 12)
h = lambda c: tuple(int(c[i:i + 2], 16) for i in (1, 3, 5))
chk("3-4 패널 색 분홍", sum(a * b for a, b in zip((0.299, 0.587, 0.114), h("#E88AAA"))), 170, 0.5)
chk("3-4 패널 색 라벤더", sum(a * b for a, b in zip((0.299, 0.587, 0.114), h("#BEAAE1"))), 182, 0.5)
# 4부
chk("4-1 8등신", 160 / 20, 8); chk("4-1 2.5등신", 160 / 64, 2.5); chk("4-1 6등신 머리", 160 / 6, 26.7, 0.05); chk("4-1 퀴즈", 160 / 40, 4)
chk("4-4 잔상 4장", 120 / 3, 40); chk("4-4 5장", 120 / 4, 30); chk("4-4 과장", 120 * 1.5 / 3, 60); chk("4-4 퀴즈", 150 / 3, 50)
chk("4-4 다리 비율 7등신", 0.5 * (1 - 1 / 7), 0.43, 0.005); chk("4-4 2.5등신 보이는 정도", 1.5 * 0.5 * (1 - 1 / 2.5) / 0.43, 1.05, 0.01)
# 5부
chk("5-2 2배 넓이", 20 * 20 / (10 * 10), 4); chk("5-2 1.5배", 15 * 15 / 100, 2.25)
for P in (P1, P2, P3, P4, P5, P6, P7):
    J = P["judge"]; sa, sb = sum(J["a"][1]), sum(J["b"][1]); txt = J["result"][0][2]
    good = f"{sb} : 주판봇 {sa}" in txt; ok &= good
    print(("OK " if good else "XX "), P["no"], "부 평가", sb, ":", sa, txt[:22])
print("전체 통과" if ok else "검산 실패"); sys.exit(0 if ok else 1)
